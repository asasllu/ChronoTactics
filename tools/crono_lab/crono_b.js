  function kit(g) {
    const P = (c, pts) => {
      g.fillStyle = pal[c];
      g.beginPath();
      pts.forEach(([x, y], i) => (i ? g.lineTo(x, y) : g.moveTo(x, y)));
      g.closePath();
      g.fill();
    };
    const E = (c, x, y, rx, ry, rot = 0) => {
      g.fillStyle = pal[c];
      g.beginPath();
      g.ellipse(x, y, rx, ry, rot, 0, Math.PI * 2);
      g.fill();
    };
    // Tapered spike from a base segment (a -> b) to a tip, bulging slightly (quadratic).
    const spike = (c, a, b, tip, bend = 0) => {
      g.fillStyle = pal[c];
      g.beginPath();
      g.moveTo(a[0], a[1]);
      const mx = (a[0] + tip[0]) / 2 + bend, my = (a[1] + tip[1]) / 2 - bend;
      g.quadraticCurveTo(mx, my, tip[0], tip[1]);
      const nx = (b[0] + tip[0]) / 2 + bend, ny = (b[1] + tip[1]) / 2 - bend;
      g.quadraticCurveTo(nx, ny, b[0], b[1]);
      g.closePath();
      g.fill();
    };
    const L = (c, pts, w) => {
      g.strokeStyle = pal[c];
      g.lineWidth = w;
      g.lineCap = 'round';
      g.lineJoin = 'round';
      g.beginPath();
      pts.forEach(([x, y], i) => (i ? g.lineTo(x, y) : g.moveTo(x, y)));
      g.stroke();
    };
    return { P, E, spike, L };
  }

